/**
 * Funções auxiliares para consulta e busca na Tabela Decisão Nutricional
 */
function getDecisaoFoodById(id) {
  if (!id) return null;
  return DECISAO_NUTRICIONAL_DATABASE.find(item => item.id === id) || null;
}

function searchDecisaoFoods(query = "") {
  if (!query || typeof query !== "string") return DECISAO_NUTRICIONAL_DATABASE;
  const q = query.toLowerCase().trim();
  return DECISAO_NUTRICIONAL_DATABASE.filter(item => 
    item.nome.toLowerCase().includes(q) || 
    item.categoria.toLowerCase().includes(q)
  );
}

